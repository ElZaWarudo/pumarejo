export interface ProviderBundleEntry {
  readonly sourceRelativePath: string;
  readonly content: string;
  readonly afterHash: string;
}

function inside(root: string, candidate: string): boolean {
  const resolvedRoot = resolve(root);
  const resolvedCandidate = resolve(candidate);
  const difference = relative(root, candidate);
  return (
    difference !== "" &&
    difference !== ".." &&
    !difference.startsWith(`..${sep}`) &&
    resolvedCandidate.startsWith(`${resolvedRoot}${sep}`)
  );
}

function safePath(root: string, sourceRelativePath: string): string {
  const candidate = resolve(root, sourceRelativePath);
  if (!inside(root, candidate)) {
    throw new IntegrationPlanError("UNSAFE_TARGET");
  }
  return candidate;
}

function packageProviderRoot(): string {
  // Both src/installer and dist/installer are two levels below the package
  // root, so this remains valid in tests and in an installed tarball.
  const packageRoot = resolve(
    dirname(fileURLToPath(import.meta.url)),
    "..",
    "..",
  );
  return resolve(packageRoot, "dist", PROVIDER_SOURCE_ROOT);
}

function developmentProviderRoot(): string {
  return resolve(
    dirname(fileURLToPath(import.meta.url)),
    "..",
    "..",
    "vendor",
    PROVIDER_NAME,
  );
}

async function regularFile(path: string): Promise<void> {
  const metadata = await lstat(path);
  if (
    metadata.isSymbolicLink() ||
    !metadata.isFile() ||
    metadata.size > MAX_PROVIDER_FILE_BYTES ||
    (await realpath(path)) !== path
  ) {
    throw new IntegrationPlanError("UNSAFE_TARGET");
  }
}

/**
 * Provider roots shipped with the running CLI: the built bundle and, in a
 * source checkout (npm git dependency or git submodule), the vendor tree.
 */
async function cliProviderRoots(): Promise<readonly string[]> {
  const roots: string[] = [];
  for (const candidate of [packageProviderRoot(), developmentProviderRoot()]) {
    try {
      roots.push(await realpath(candidate));
    } catch {
      // Absent in this layout.
    }
  }
  return roots;
}

export async function resolveProviderSourceRoot(): Promise<string> {
  const packaged = packageProviderRoot();
  try {
    const metadata = await lstat(packaged);
    if (metadata.isSymbolicLink() || !metadata.isDirectory()) {
      throw new IntegrationPlanError("UNSAFE_TARGET");
    }
    if ((await realpath(packaged)) !== packaged) {
      throw new IntegrationPlanError("UNSAFE_TARGET");
    }
    return packaged;
  } catch (error) {
    if (error instanceof IntegrationPlanError) throw error;
    const development = developmentProviderRoot();
    try {
      const metadata = await lstat(development);
      if (metadata.isSymbolicLink() || !metadata.isDirectory()) {
        throw new IntegrationPlanError("UNSAFE_TARGET");
      }
      if ((await realpath(development)) !== development) {
        throw new IntegrationPlanError("UNSAFE_TARGET");
      }
      return development;
    } catch (fallbackError) {
      if (fallbackError instanceof IntegrationPlanError) throw fallbackError;
      throw new IntegrationPlanError("WRITE_FAILED", { cause: fallbackError });
    }
  }
}

export async function readProviderBundle(): Promise<
  readonly ProviderBundleEntry[]
> {
  const root = await resolveProviderSourceRoot();
  const entries: ProviderBundleEntry[] = [];
  for (const sourceRelativePath of PROVIDER_SOURCE_ALLOWLIST) {
    const path = safePath(root, sourceRelativePath);
    try {
      await regularFile(path);
      // The provider is text. Git stores it with LF; a Windows checkout may
      // turn it into CRLF. LF is canonical so the bundle never depends on the
      // building machine's checkout.
      const content = (await readFile(path, "utf8")).replaceAll("\r\n", "\n");
      entries.push({
        sourceRelativePath,
        content,
        afterHash: hash(content),
      });
    } catch (error) {
      if (error instanceof IntegrationPlanError) throw error;
      throw new IntegrationPlanError("WRITE_FAILED", { cause: error });
    }
  }
  return entries;
}

/**
 * Whether staged provider text matches a recorded hash, ignoring only line
 * endings. Consumers may commit the provider and let Git rewrite CRLF/LF.
 */
export function providerContentMatches(
  content: string,
  expectedHash: string,
): boolean {
  const lf = content.replaceAll("\r\n", "\n");
  return (
    hash(content) === expectedHash ||
    hash(lf) === expectedHash ||
    hash(lf.replaceAll("\n", "\r\n")) === expectedHash
  );
}

export function providerAttribution(sourceRelativePath: string): string {
  return `${PROVIDER_ATTRIBUTION_PREFIX}${sourceRelativePath}`;
}

export function providerSourcePathFromAttribution(
  attribution: readonly string[],
): string | undefined {
  if (attribution.length !== 1) return undefined;
  const value = attribution[0] ?? "";
  if (!value.startsWith(PROVIDER_ATTRIBUTION_PREFIX)) return undefined;
  const sourceRelativePath = value.slice(PROVIDER_ATTRIBUTION_PREFIX.length);
  return PROVIDER_SOURCE_ALLOWLIST.includes(sourceRelativePath)
    ? sourceRelativePath
    : undefined;
}

async function listStagedFiles(root: string): Promise<{
  readonly files: readonly string[];
  readonly directories: readonly string[];
}> {
  const files: string[] = [];
  const directories: string[] = [];
  const visit = async (directory: string, prefix: string): Promise<void> => {
    const entries = await readdir(directory, { withFileTypes: true });
    for (const entry of entries) {
      const sourceRelativePath = prefix
        ? `${prefix}/${entry.name}`
        : entry.name;
      const path = safePath(root, sourceRelativePath);
      if (entry.isSymbolicLink())
        throw new IntegrationPlanError("UNSAFE_TARGET");
      if (entry.isDirectory()) {
        directories.push(sourceRelativePath.replaceAll("\\", "/"));
        await visit(path, sourceRelativePath);
      } else if (entry.isFile()) {
        await regularFile(path);
        files.push(sourceRelativePath.replaceAll("\\", "/"));
      } else {
        throw new IntegrationPlanError("UNSAFE_TARGET");
      }
    }
  };
  await visit(root, "");
  return { files: files.sort(), directories: directories.sort() };
}

export async function validateProviderStaging(
  projectRoot: string,
  expectedEntries: readonly { readonly relativePath: string }[],
  // Line endings are always reconciled; the option is kept for callers.
  _options: { readonly reconcileLineEndings?: boolean } = {},
): Promise<void> {
  const stageRoot = safePath(resolve(projectRoot), PROVIDER_STAGED_ROOT);
  try {
    const metadata = await lstat(stageRoot);
    if (metadata.isSymbolicLink() || !metadata.isDirectory()) {
      throw new IntegrationPlanError("UNSAFE_TARGET");
    }
    if ((await realpath(stageRoot)) !== stageRoot) {
      throw new IntegrationPlanError("UNSAFE_TARGET");
    }
  } catch (error) {
    if (error instanceof IntegrationPlanError) throw error;
    throw new IntegrationPlanError("ALREADY_INTEGRATED_MODIFIED", {
      cause: error,
    });
  }
  const listed = await listStagedFiles(stageRoot);
  const actual = listed.files;
  const expected = expectedEntries
    .map((entry) => {
      if (!entry.relativePath.startsWith(`${PROVIDER_STAGED_ROOT}/`)) {
        throw new IntegrationPlanError("ALREADY_INTEGRATED_MODIFIED");
      }
      return entry.relativePath.slice(`${PROVIDER_STAGED_ROOT}/`.length);
    })
    .sort();
  if (
    actual.length !== expected.length ||
    actual.some((path, index) => path !== expected[index])
  ) {
    throw new IntegrationPlanError("ALREADY_INTEGRATED_MODIFIED");
  }
  const expectedDirectories = new Set<string>();
  for (const sourceRelativePath of expected) {
    const segments = sourceRelativePath.split("/");
    segments.pop();
    for (let index = 1; index <= segments.length; index += 1) {
      expectedDirectories.add(segments.slice(0, index).join("/"));
    }
  }
  if (
    listed.directories.length !== expectedDirectories.size ||
    listed.directories.some((directory) => !expectedDirectories.has(directory))
  ) {
    throw new IntegrationPlanError("ALREADY_INTEGRATED_MODIFIED");
  }
  const bundle = await readProviderBundle();
  const expectedSources = new Map(
    bundle.map((entry) => [entry.sourceRelativePath, entry.content]),
  );
  const drifted: string[] = [];
  for (const sourceRelativePath of actual) {
    const stagedPath = safePath(stageRoot, sourceRelativePath);
    const source = await readFile(stagedPath, "utf8");
    const expected = expectedSources.get(sourceRelativePath);
    if (
      expected === undefined ||
      source.replaceAll("\r\n", "\n") !== expected.replaceAll("\r\n", "\n")
    ) {
      drifted.push(sourceRelativePath);
    }
  }
  if (drifted.length > 0) throw new ProviderDriftError(drifted);
}

/** Staged provider files whose content differs beyond line endings. */
export class ProviderDriftError extends IntegrationPlanError {
  readonly files: readonly string[];

  constructor(files: readonly string[]) {
    super("ALREADY_INTEGRATED_MODIFIED");
    this.files = [...files];
  }
}

/** Characters allowed in an external provider path written into Cargo.toml. */
const EXTERNAL_PROVIDER_PATH = /^[A-Za-z0-9._@+\- /]+$/u;
const MAX_EXTERNAL_PROVIDER_PATH_LENGTH = 1_024;

/**
 * Validate the shape of an external provider path as recorded in the
 * integration manifest and written to Cargo.toml: relative to the directory
 * holding src-tauri/Cargo.toml, forward slashes, and never inside a .pumarejo directory (the staged copy's home).
 */
export function isExternalProviderCargoPath(value: unknown): value is string {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= MAX_EXTERNAL_PROVIDER_PATH_LENGTH &&
    EXTERNAL_PROVIDER_PATH.test(value) &&
    !value.startsWith("/") &&
    !value.endsWith("/") &&
    !value
      .split("/")
      .some(
        (segment) =>
          segment === "" || segment === "." || segment === ".pumarejo",
      )
  );
}

/**
 * Turn a user-supplied provider directory (absolute, or relative to `base`)
 * into the Cargo path dependency seen from `cargoDirectory`.
 */
export function externalProviderCargoPath(
  cargoDirectory: string,
  providerPath: string,
  base: string = process.cwd(),
): string {
  const absolute = resolve(base, providerPath);
  const fromCargo = relative(cargoDirectory, absolute);
  if (fromCargo === "" || isAbsolute(fromCargo)) {
    throw new IntegrationPlanError("PROVIDER_PATH_INVALID");
  }
  const cargoPath = fromCargo.split(sep).join("/");
  if (!isExternalProviderCargoPath(cargoPath)) {
    throw new IntegrationPlanError("PROVIDER_PATH_INVALID");
  }
  return cargoPath;
}

export interface ExternalProviderInspection {
  /** The directory exists and holds the provider crate at a supported version. */
  readonly valid: boolean;
  readonly reason?: "missing" | "not-provider" | "unsupported-version";
  readonly packageVersion?: string;
  /**
   * How the external provider relates to the provider this CLI ships:
   * the same directory, identical content, or different content.
   */
  readonly origin?: "cli" | "identical" | "different";
  readonly differingFiles?: readonly string[];
}

/** Inspect an external provider referenced from `cargoDirectory`. */
export async function inspectExternalProvider(
  cargoDirectory: string,
  cargoPath: string,
): Promise<ExternalProviderInspection> {
  if (!isExternalProviderCargoPath(cargoPath)) {
    return { valid: false, reason: "missing" };
  }
  let root: string;
  let manifest: string;
  try {
    root = await realpath(resolve(cargoDirectory, cargoPath));
    if (!(await lstat(root)).isDirectory()) {
      return { valid: false, reason: "missing" };
    }
    const manifestPath = resolve(root, "Cargo.toml");
    const metadata = await lstat(manifestPath);
    if (
      metadata.isSymbolicLink() ||
      !metadata.isFile() ||
      metadata.size > MAX_PROVIDER_FILE_BYTES
    ) {
      return { valid: false, reason: "not-provider" };
    }
    manifest = await readFile(manifestPath, "utf8");
  } catch {
    return { valid: false, reason: "missing" };
  }
  let name: unknown;
  let version: unknown;
  try {
    const parsed = parseToml(manifest) as {
      package?: { name?: unknown; version?: unknown };
    };
    name = parsed.package?.name;
    version = parsed.package?.version;
  } catch {
    return { valid: false, reason: "not-provider" };
  }
  if (name !== PROVIDER_NAME || typeof version !== "string") {
    return { valid: false, reason: "not-provider" };
  }
  // The consumer dependency requires `version = "1"`, i.e. any 1.x release.
  if (!version.startsWith(`${TAURI_WEBDRIVER_PLUGIN_VERSION}.`)) {
    return {
      valid: false,
      reason: "unsupported-version",
      packageVersion: version,
    };
  }

  if ((await cliProviderRoots()).includes(root)) {
    return { valid: true, packageVersion: version, origin: "cli" };
  }
  const differingFiles: string[] = [];
  for (const entry of await readProviderBundle()) {
    try {
      const path = safePath(root, entry.sourceRelativePath);
      await regularFile(path);
      const content = (await readFile(path, "utf8")).replaceAll("\r\n", "\n");
      if (hash(content) !== entry.afterHash) {
        differingFiles.push(entry.sourceRelativePath);
      }
    } catch {
      differingFiles.push(entry.sourceRelativePath);
    }
  }
  return differingFiles.length === 0
    ? { valid: true, packageVersion: version, origin: "identical" }
    : {
        valid: true,
        packageVersion: version,
        origin: "different",
        differingFiles,
      };
}
